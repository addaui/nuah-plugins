#!/usr/bin/env node
// Writes `contract.d.ts` from a `describe` snapshot: for every operation, its input and output types, so the Face's calls are typed.
// Usage: nuah-link-gen <describe.json> <out.d.ts>
import { readFileSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const [, , from, to] = process.argv;
if (!from || !to) { console.error("usage: nuah-link-gen <describe.json> <out.d.ts>"); process.exit(2); }

const describe = JSON.parse(readFileSync(from, "utf8"));
const ident = (op, part) => `${op.replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))}${part}`.replace(/^./, (c) => c.toUpperCase());
const options = { bannerComment: "", additionalProperties: false, unknownAny: true, strictIndexSignatures: true, format: false, declareExternallyReferenced: true };

let out = `// Generated by nuah-link-gen from a describe snapshot (contract ${describe.contract}). Do not edit.\n/* eslint-disable */\n\n`;
const entries = [];
for (const op of Object.keys(describe.operations).sort()) {
  const d = describe.operations[op];
  for (const [part, schema] of [["Input", d.input], ["Output", d.output]]) {
    const name = ident(op, part);
    out += (await compile({ ...schema, title: name }, name, options)).trim() + "\n\n";
  }
  entries.push(`  ${JSON.stringify(op)}: { input: ${ident(op, "Input")}; output: ${ident(op, "Output")}; kind: ${JSON.stringify(d.kind)} };`);
}
out += `export interface Ops {\n${entries.join("\n")}\n}\n\nexport const contract = ${JSON.stringify(describe.contract)};\n`;
out = out.replace(/export const contract = (".*");\n$/, "export declare const contract: $1;\n");
writeFileSync(to, out);
console.log(`${entries.length} operations written to ${to}`);
